"""Generate DATA_SUMMARY.md - a basic, reproducible profile of the three raw parquet files.

Usage:  python make_data_summary.py
Reads only the raw files (column by column to keep memory low).
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd
import pyarrow.parquet as pq

from src.config import DAILY, FAILURES, JOBS, ROOT
from src.data import categorize_downtime

OUT_MD = ROOT / "DATA_SUMMARY.md"


def md_table(df: pd.DataFrame, floatfmt: str = "{:,.2f}", index: bool = True) -> str:
    d = df.reset_index() if index else df
    def f(v):
        if isinstance(v, (float, np.floating)):
            return "" if np.isnan(v) else (f"{v:,.0f}" if abs(v) >= 1000 else floatfmt.format(v))
        if isinstance(v, (int, np.integer)):
            return str(v) if 1900 <= v <= 2100 else f"{v:,}"
        return str(v).replace("|", "/")
    lines = ["| " + " | ".join(map(str, d.columns)) + " |", "|" + "---|" * len(d.columns)]
    lines += ["| " + " | ".join(f(v) for v in row) + " |" for row in d.itertuples(index=False)]
    return "\n".join(lines)


def vc(s: pd.Series, n: int = 10, name: str = "rows") -> pd.DataFrame:
    s2 = s.astype(object).where(s.notna(), "(missing)")
    c = s2.value_counts().head(n)
    return pd.DataFrame({name: c, "%": 100 * c / len(s)})


def col(path: Path, cols: list[str], filters=None) -> pd.DataFrame:
    return pq.read_table(path, columns=cols, filters=filters).to_pandas()


def main():
    md: list[str] = []
    w = md.append
    w(f"# Data Summary\n\n_Generated by `make_data_summary.py` on {date.today()} from the raw competition files._\n")

    # ------------------------------------------------------------------ overview
    files = [(DAILY, "Daily time series (well x day)"), (JOBS, "Event log - one row per job"),
             (FAILURES, "Event log - one row per failure")]
    ov = []
    for p, kind in files:
        m = pq.ParquetFile(p).metadata
        u = col(p, ["uwi"])["uwi"].nunique()
        ov.append({"file": p.name, "type": kind, "rows": m.num_rows, "wells": u, "columns": m.num_columns,
                   "size_MB": p.stat().st_size / 1e6})
    w("## 1. Files\n")
    w(md_table(pd.DataFrame(ov), index=False))
    w("\nAll three files join on `uwi` (well identifier). Grain differs: joining daily rows to events repeats rows.\n")

    # ------------------------------------------------------------------ daily production
    w("## 2. `daily_production.parquet`\n")
    meta = col(DAILY, ["uwi", "production_date", "well_daily_status", "flow_direction", "primary_fluid_type",
                       "province", "field_operating_area", "facility_name"])
    meta["production_date"] = pd.to_datetime(meta["production_date"])
    w(f"- **Date range:** {meta.production_date.min().date()} to {meta.production_date.max().date()} "
      f"({meta.production_date.nunique():,} days)")
    w(f"- **Wells:** {meta.uwi.nunique():,} total - "
      f"{meta.loc[meta.flow_direction == 'production', 'uwi'].nunique():,} producers, "
      f"{meta.loc[meta.flow_direction == 'injection', 'uwi'].nunique():,} injectors (some wells switch)")
    w(f"- **Operating areas:** {meta.field_operating_area.nunique()}, **facilities:** {meta.facility_name.nunique()}")
    dup = meta.duplicated(["uwi", "production_date"]).sum()
    w(f"- **Duplicate well-day rows:** {dup}\n")

    w("### Status, direction, fluid, province\n")
    for c, n in [("well_daily_status", 8), ("flow_direction", 3), ("primary_fluid_type", 11), ("province", 4)]:
        w(f"**`{c}`**\n\n" + md_table(vc(meta[c], n)) + "\n")
    w("**Top 12 operating areas by well-days**\n\n" + md_table(vc(meta.field_operating_area, 12)) + "\n")
    del meta

    # coverage + numeric stats
    num_cols = ["hours_down", "hours_on_prod", "lost_oil_m3", "oil_produced_m3", "water_produced_m3",
                "gas_produced_e3m3", "injection_volume_m3", "injected_water_m3", "injected_polymer_m3",
                "tubing_pressure_kpa", "casing_pressure_kpa", "injection_pressure_kpa", "pump_efficiency_pct",
                "pcp_pump_rpm", "pcp_pump_displacement_m3d100rpm", "pcp_pump_rod_torque_ftlb",
                "pcp_pump_electric_current_a", "pcp_pump_volume_throughput_m3d", "hydraulic_pressure_psi",
                "choke_open_pct"]
    w("### Numeric columns - coverage and distribution (all rows)\n")
    rows = []
    for c in num_cols:
        s = col(DAILY, [c])[c].astype("float64")
        q = s.quantile([0.01, 0.5, 0.99])
        rows.append({"column": c, "non-null %": 100 * s.notna().mean(), "min": s.min(), "p1": q[0.01],
                     "median": q[0.5], "p99": q[0.99], "max": s.max(), "negatives": int((s < 0).sum())})
    w(md_table(pd.DataFrame(rows), index=False))
    w("\nNotes: `pump_efficiency_pct` is a 0-1 decimal, not 0-100. Max values far above p99 (e.g. tubing "
      "pressure 999,999) are placeholders or entry errors.\n")

    # text columns coverage
    txt = ["downtime_code_1", "downtime_code_2", "downtime_code_3", "facility_name", "on_production_date",
           "pcp_pump_make", "pcp_pump_model", "pcp_pump_comment"]
    cov = pd.DataFrame({c: [100 * col(DAILY, [c])[c].notna().mean()] for c in txt}, index=["non-null %"]).T
    w("### Text / categorical columns - coverage\n\n" + md_table(cov.rename_axis("column")) + "\n")

    # yearly production (producers)
    p = col(DAILY, ["uwi", "production_date", "oil_produced_m3", "water_produced_m3", "gas_produced_e3m3",
                    "lost_oil_m3", "hours_on_prod", "hours_down", "downtime_code_1", "well_daily_status"],
            filters=[("flow_direction", "==", "production")])
    p["year"] = pd.to_datetime(p["production_date"]).dt.year
    for c in ["oil_produced_m3", "water_produced_m3"]:
        p[c] = p[c].where(p[c] >= 0)
    y = p.groupby("year").agg(oil_m3=("oil_produced_m3", "sum"), water_m3=("water_produced_m3", "sum"),
                              gas_e3m3=("gas_produced_e3m3", "sum"), reported_lost_oil_m3=("lost_oil_m3", "sum"),
                              wells_reporting=("uwi", "nunique"),
                              producing_well_days=("well_daily_status", lambda s: int((s == "Producing").sum())),
                              days=("production_date", "nunique"))
    y["water_cut_%"] = 100 * y.water_m3 / (y.oil_m3 + y.water_m3)
    y["oil_bbl_per_day"] = y.oil_m3 * 6.2898 / y.days
    w("### Yearly production (producing wells)\n")
    w(md_table(y.drop(columns="days")))
    dn = p[p.hours_down > 0]
    w(f"\n2026 is partial (to {pd.to_datetime(p.production_date).max().date()}); compare `oil_bbl_per_day` "
      f"rather than totals. `lost_oil_m3` is filled on {100 * dn.lost_oil_m3.notna().mean():.1f}% of downtime "
      f"days (it looks sparse overall only because most days have no downtime); "
      f"{100 * (dn.lost_oil_m3 > 0).mean():.0f}% of downtime days carry a non-zero value.\n")

    # downtime
    d = p[p.hours_down > 0].copy()
    d["category"] = d.downtime_code_1.map(lambda x: categorize_downtime(x))
    dc = d.groupby("category").agg(down_well_days=("hours_down", "size"), hours_down=("hours_down", "sum"),
                                   reported_lost_oil_m3=("lost_oil_m3", "sum")).sort_values("hours_down",
                                                                                             ascending=False)
    dc["% of hours"] = 100 * dc.hours_down / dc.hours_down.sum()
    w("### Downtime by cause (producers, rows with hours_down > 0)\n")
    w(f"{p.downtime_code_1.nunique()} raw `downtime_code_1` values were grouped into the categories below "
      "using keyword rules (`src/data.py::categorize_downtime`).\n")
    w(md_table(dc))
    w("\n**Top 15 raw downtime codes by hours down**\n")
    raw = d.groupby("downtime_code_1").agg(hours_down=("hours_down", "sum"), reported_lost_oil_m3=("lost_oil_m3", "sum"))
    w(md_table(raw.sort_values("hours_down", ascending=False).head(15)) + "\n")
    del p, d

    # data quality
    w("### Data-quality flags\n")
    dq = []
    s = col(DAILY, ["tubing_pressure_kpa"])["tubing_pressure_kpa"]
    dq.append(("Tubing pressure >= 99,999 kPa (placeholder)", int((s >= 99999).sum())))
    for c in ["oil_produced_m3", "water_produced_m3", "injection_volume_m3", "casing_pressure_kpa"]:
        s = col(DAILY, [c])[c]
        dq.append((f"Negative `{c}`", int((s < 0).sum())))
    s = col(DAILY, ["pump_efficiency_pct"])["pump_efficiency_pct"]
    dq.append(("`pump_efficiency_pct` > 3 (300%)", int((s > 3).sum())))
    s = col(DAILY, ["choke_open_pct"])["choke_open_pct"]
    dq.append(("`choke_open_pct` > 100", int((s > 100).sum())))
    dq.append(("Duplicate well-day rows", int(dup)))
    mk = col(DAILY, ["pcp_pump_make"])["pcp_pump_make"].dropna()
    dq.append(("Distinct raw pump-make spellings (e.g. Weatherford/WEATHERFORD)", int(mk.nunique())))
    w(md_table(pd.DataFrame(dq, columns=["check", "count"]), index=False))

    # stale readings
    st = []
    pr = col(DAILY, ["uwi", "production_date", "tubing_pressure_kpa", "casing_pressure_kpa", "pcp_pump_rpm",
                     "pcp_pump_rod_torque_ftlb", "pcp_pump_electric_current_a", "pump_efficiency_pct",
                     "oil_produced_m3"], filters=[("flow_direction", "==", "production")])
    pr = pr.sort_values(["uwi", "production_date"])
    g = pr.groupby("uwi")
    for c in pr.columns[2:]:
        prev = g[c].shift()
        m = pr[c].notna() & prev.notna()
        st.append({"tag": c, "repeat of previous day %": 100 * float((pr.loc[m, c] == prev[m]).mean())})
    del pr
    w("\n**Repeated readings (producers):** share of daily values identical to the previous day. Values near "
      "100% indicate manually entered readings carried forward, not a live sensor signal.\n")
    w(md_table(pd.DataFrame(st), index=False) + "\n")

    # ------------------------------------------------------------------ jobs
    j = pd.read_parquet(JOBS)
    j["start_date"] = pd.to_datetime(j["start_date"])
    w("## 3. `well_jobs.parquet`\n")
    w(f"- **Date range:** {j.start_date.min().date()} to {j.start_date.max().date()}; "
      f"**{len(j):,} jobs** on **{j.uwi.nunique():,} wells**")
    empty = [c for c in j.columns if j[c].notna().mean() < 0.01]
    w(f"- **Empty / near-empty columns:** {', '.join(f'`{c}`' for c in empty)}")
    w(f"- **Negative `job_duration_days`:** {(j.job_duration_days < 0).sum()} rows; median duration "
      f"{j.job_duration_days.median():.2f} days")
    w(f"- **AFE budget present:** {100 * j.afe_cost_total.notna().mean():.1f}% of jobs; "
      f"`field_est_total` present on all (median ${j.field_est_total.median():,.0f}, "
      f"{(j.field_est_total < 0).sum()} negative)\n")
    jc = j.groupby("job_category").agg(jobs=("uwi", "size"), wells=("uwi", "nunique"),
                                       median_cost=("field_est_total", "median"), total_cost=("field_est_total", "sum"),
                                       median_days=("job_duration_days", "median"))
    w("**By job category (top 10 by count)**\n\n" + md_table(jc.sort_values("jobs", ascending=False).head(10)) + "\n")
    w("**Top 15 job types**\n\n" + md_table(vc(j.job_type, 15, "jobs")) + "\n")
    w("**Top 15 job subtypes**\n\n" + md_table(vc(j.job_subtype, 15, "jobs")) + "\n")
    yj = j.groupby([j.start_date.dt.year.rename("year"), "job_category"]).size().unstack(fill_value=0)
    yj = yj[[c for c in ["Rod Truck", "Workover", "Drilling", "Completion", "Abandon"] if c in yj]]
    w("**Jobs per year (main categories)**\n\n" + md_table(yj) + "\n")
    lens = j.summary.dropna().str.split().str.len()
    w(f"Free text: `objective` filled on {100 * j.objective.notna().mean():.0f}% of jobs, `summary` on "
      f"{100 * j.summary.notna().mean():.0f}% (median {lens.median():.0f} words, max {lens.max():,}).\n")

    # ------------------------------------------------------------------ failures
    f = pd.read_parquet(FAILURES)
    f["failure_start_date"] = pd.to_datetime(f["failure_start_date"])
    w("## 4. `production_failures.parquet`\n")
    w(f"- **{len(f):,} failures** on **{f.uwi.nunique():,} wells**, "
      f"{f.failure_start_date.min().date()} to {f.failure_start_date.max().date()}")
    w(f"- **Failures per well:** median {f.uwi.value_counts().median():.0f}, max {f.uwi.value_counts().max()}")
    empty = [c for c in f.columns if f[c].notna().mean() < 0.01]
    w(f"- **Empty / near-empty columns:** {', '.join(f'`{c}`' for c in empty)}\n")
    w("**Failures by year** - the log effectively starts in 2025:\n\n" +
      md_table(vc(f.failure_start_date.dt.year, 10, "failures").sort_index()) + "\n")
    w("**`failure_type`** (component)\n\n" + md_table(vc(f.failure_type, 8, "failures")) + "\n")
    w("**`cause`**\n\n" + md_table(vc(f.cause, 12, "failures")) + "\n")
    w("**`failure_detail`** (top 12)\n\n" + md_table(vc(f.failure_detail, 12, "failures")) + "\n")
    w("**By operating area**\n\n" + md_table(vc(f.field_operating_area, 10, "failures")) + "\n")
    w(f"`failure_comments` is filled on {100 * f.failure_comments.notna().mean():.0f}% of rows and often "
      "holds the break depth or rod number (e.g. \"Broken corod @ 303m\").\n")

    # ------------------------------------------------------------------ joins
    w("## 5. How the files connect\n")
    du = set(col(DAILY, ["uwi"])["uwi"].unique())
    jm = j[["uwi", "start_date", "job_category"]]
    m = f[["uwi", "failure_start_date"]].merge(jm, on="uwi", how="left")
    m["dt"] = (m.start_date - m.failure_start_date).dt.days
    hit = m[m.dt.between(-3, 14)].sort_values("dt").drop_duplicates(["uwi", "failure_start_date"])
    w(f"- Job wells found in daily data: {100 * j.uwi.isin(du).mean():.1f}%; failure wells found: "
      f"{100 * f.uwi.isin(du).mean():.1f}%")
    w(f"- Failures with a service job on the same well within -3..+14 days: "
      f"{100 * len(hit) / len(f.drop_duplicates(['uwi', 'failure_start_date'])):.1f}% "
      f"(mostly {hit.job_category.value_counts().head(2).to_dict()})")
    w("- So each failure can be costed through its repair job, and repair jobs can stand in for failures "
      "in 2021-2024, before the failure log starts.\n")

    w("## 6. Key caveats for analysis\n")
    w("1. **Failure log covers 2025-26 only**: use repair jobs as the failure label for earlier years.\n"
      "2. **Pressure, torque, current and RPM are mostly carried-forward manual readings**: treat as levels, "
      "not as early-warning signals. Daily oil and pump efficiency are the signals that actually change.\n"
      "3. **Reported lost oil covers outage days only**: it misses the production decline *before* a "
      "failure. Re-estimating it (baseline rate x hours down) reproduces the reported totals and extends to "
      "that hidden loss.\n"
      "4. **'Uneconomic - Long Term Shut In' dominates downtime hours** but is a business decision, not a "
      "failure; separate it from avoidable downtime.\n"
      "5. **2026 is a partial year**; compare per-day rates.\n"
      "6. **Placeholders, negatives and inconsistent labels** need cleaning (see data-quality flags).\n")

    OUT_MD.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {OUT_MD}")


if __name__ == "__main__":
    main()
